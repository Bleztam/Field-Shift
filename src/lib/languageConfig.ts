/** Addis AI language codes we support. No other codes are accepted. */
export const ADDIS_LANGUAGE_CODES = ["am", "om", "ti", "sid", "wal"] as const;
export type AddisLanguageCode = (typeof ADDIS_LANGUAGE_CODES)[number];

export function isAddisLanguageCode(v: unknown): v is AddisLanguageCode {
  return (
    typeof v === "string" &&
    (ADDIS_LANGUAGE_CODES as readonly string[]).includes(v)
  );
}

/** Script the Gemini monologue must use for a language. */
export type LanguageScript = "ethiopic" | "latin";

export interface SupportedLanguage {
  code: AddisLanguageCode;
  /** Name in the language itself (shown on the picker buttons). */
  nativeName: string;
  englishName: string;
  /**
   * BCP-47 tag for SpeechRecognition.
   * TODO verify: browser SR support for om/ti/sid/wal is spotty — when SR is
   * unavailable the UI falls back to typed text + crop chips.
   */
  speechRecognitionLang: string;
  script: LanguageScript;
  /** Language name used inside Gemini prompts. */
  promptName: string;
  // TODO verify (native-speaker review pending) — everything below this line
  // is user-facing prose in the target language.
  greeting: string;
  errorBody: string;
  listening: string;
  thinking: string;
  /** Appended to every monologue in code. Never generated by the LLM. */
  closingLine: string;
  /**
   * Deterministic offline/Gemini-down monologue template (first person).
   * TODO verify — native-speaker review pending for all languages.
   */
  fallbackScript: string;
  fallbackSubtitles: string;
  /**
   * Local crop glosses for keyword extraction, keyed by canonical crop id.
   * TODO verify non-Amharic maps with agronomists per language.
   */
  cropNames: Record<string, string[]>;
}

