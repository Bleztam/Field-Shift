/**
 * Ethiopian region → most likely supported language.
 * TODO verify: language geography is approximate and multilingual in reality;
 * this map only picks a DEFAULT — the farmer can always override.
 */
export type RegionKey =
  | "oromia"
  | "amhara"
  | "addis_ababa"
  | "tigray"
  | "sidama"
  | "snnpr" // South / Central Ethiopia incl. Wolaita
  | "other"
  | "unknown";

export const REGION_LANGUAGE_MAP: Record<
  Exclude<RegionKey, "unknown">,
  { default: AddisLanguageCode; alsoOffer?: AddisLanguageCode; note?: string }
> = {
  oromia: { default: "om" },
  amhara: { default: "am" },
  addis_ababa: { default: "am", alsoOffer: "om" },
  tigray: { default: "ti" },
  sidama: { default: "sid" },
  snnpr: { default: "wal" },
  other: {
    default: "am",
    note: "Local language not yet available for speech — Amharic offered.",
  },
};

const LANGUAGE_STORAGE_KEY = "fieldshift:language";

export function loadSavedLanguage(): AddisLanguageCode | null {
  try {
    if (typeof window === "undefined") return null;
    const v = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return isAddisLanguageCode(v) ? v : null;
  } catch {
    return null;
  }
}

export function saveLanguageChoice(code: AddisLanguageCode): void {
  try {
    if (typeof window === "undefined") return;
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, code);
  } catch {
    // private mode — choice just won't persist
  }
}

/**
 * Final spoken language: saved farmer choice > region default > Amharic.
 * `suggested` is true when the value came from the region default (so the UI
 * can label it "suggested for your area").
 */
export function resolveLanguage(
  saved: AddisLanguageCode | null,
  regionKey: RegionKey | null | undefined
): { code: AddisLanguageCode; suggested: boolean } {
  if (saved) return { code: saved, suggested: false };
  if (regionKey && regionKey !== "unknown") {
    return { code: REGION_LANGUAGE_MAP[regionKey].default, suggested: true };
  }
  return { code: "am", suggested: false };
}

/** Human label for the language chip: native name (short, recognizable). */
export function languageDisplay(code: AddisLanguageCode): string {
  return SUPPORTED_LANGUAGES[code].nativeName;
}
